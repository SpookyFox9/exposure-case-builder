"""Build a SYNTHETIC earlier pull from a saved export, to demonstrate the trend diff offline.

This is not a real earlier pull. It applies fixed, deterministic edits to the records of an export so that most
trend categories have examples (not ``not_seen_not_rescanned``, because no host is removed):

- records first seen in the last 14 days are dropped (new since the baseline);
- a share of older records are dropped (newly visible);
- some FIXED findings are put back to OPEN (fixed recorded), only if Tenable's fix date is after the baseline;
- some REOPENED findings are put back to FIXED (reopened), only if Tenable fixed them on or before the baseline
  and saw them again after it; a finding without those dates never changes state;
- some critical findings are lowered one level (severity raised) and some high ones raised one level (severity
  lowered);
- some extra findings that exist only in the baseline are added on hosts that are still scanned (not seen,
  rescanned).

Timestamps move back 14 days and scan ids are replaced by derived ones that start with ``synthetic-``. Plugin
output is not copied. A file named SYNTHETIC is written next to the chunks, and the trend tool reports the label
wherever results appear.

The output goes to a directory you name (it must be empty or new), is never inside the source, and is not meant to
be committed. For real use, save a second real pull with ``scripts/fetch_tenable.py`` instead.

Usage:
    uv run python scripts/make_baseline.py data/sample <output-dir>

Timestamps are rewritten to whole seconds (the fraction is dropped), which is fine for a demonstration.
"""

from __future__ import annotations

import argparse
import copy
import hashlib
import json
import logging
import sys
import uuid
from datetime import datetime, timedelta
from pathlib import Path
from typing import Any

from exposure_case.baseline import SYNTHETIC_MARKER, SYNTHETIC_SCAN_PREFIX
from exposure_case.ingest import IngestError, iter_raw_records

log = logging.getLogger("make_baseline")

SHIFT = timedelta(days=14)
NAMESPACE = uuid.UUID("5d3c1c0e-9a53-5a0f-8f25-3b0f3a3b6d11")  # fixed, so output is reproducible
BUCKETS = 20
DROP_BUCKET, LOWER_BUCKET, EXTRA_BUCKET, RAISE_BUCKET = 0, 1, 2, 3
EXTRA_PORT_BASE = 61000
MARKER_TEXT = "Generated by scripts/make_baseline.py from an existing export. Not a real earlier pull.\n"
_TS_FORMAT = "%Y-%m-%dT%H:%M:%S"


def _parse(value: str) -> datetime:
    return datetime.strptime(value.replace(" ", "T")[:19], _TS_FORMAT)


def _format(value: datetime) -> str:
    return f"{value.strftime(_TS_FORMAT)}.000Z"


def _bucket(finding_id: str) -> int:
    return int(hashlib.sha256(finding_id.encode("utf-8")).hexdigest()[:8], 16) % BUCKETS


def _scan_id(original: str) -> str:
    return SYNTHETIC_SCAN_PREFIX + str(uuid.uuid5(NAMESPACE, f"scan:{original}"))


def _after(raw: dict[str, Any], field: str, cutoff: datetime) -> bool | None:
    """Whether Tenable's own date for an event is after the baseline; None when Tenable gives no date."""
    value = raw.get(field)
    return _parse(value) > cutoff if value else None


def _baseline_state(raw: dict[str, Any], cutoff: datetime) -> str | None:
    """An earlier state only where Tenable's own dates support it; None means keep the current state.

    FIXED now was OPEN then if Tenable fixed it after the baseline. REOPENED now was FIXED then if Tenable fixed it
    on or before the baseline and saw it again after. A missing date never produces a change.
    """
    if raw.get("state") == "FIXED" and _after(raw, "last_fixed", cutoff) is True:
        return "OPEN"
    fixed_before = _after(raw, "last_fixed", cutoff) is False
    if raw.get("state") == "REOPENED" and fixed_before and _after(raw, "resurfaced_date", cutoff) is True:
        return "FIXED"
    return None


def _older(raw: dict[str, Any], bucket: int, cutoff: datetime) -> dict[str, Any]:
    """The same finding as it looked 14 days earlier."""
    out = copy.deepcopy(raw)  # the source record is never touched
    out.pop("output", None)  # plugin output is never copied into a synthetic baseline
    first = _parse(raw["first_found"])
    out["last_found"] = _format(max(first, _parse(raw["last_found"]) - SHIFT))
    earlier = _baseline_state(raw, cutoff) if bucket % 2 == 0 else None
    if earlier:
        out["state"] = earlier
    if bucket == LOWER_BUCKET and raw.get("severity") == "critical":
        out["severity"] = "high"  # now critical: severity raised
    elif bucket == RAISE_BUCKET and raw.get("severity") == "high":
        out["severity"] = "critical"  # now high: severity lowered
    scan = dict(out.get("scan") or {})
    if scan.get("uuid"):
        scan["uuid"] = _scan_id(scan["uuid"])
    if scan.get("started_at"):
        scan["started_at"] = _format(_parse(scan["started_at"]) - SHIFT)
    out["scan"] = scan
    return out


def _extra(raw: dict[str, Any], older: dict[str, Any], bucket: int) -> dict[str, Any]:
    """A baseline-only finding on the same host: present then, absent now."""
    out = copy.deepcopy(older)
    out["finding_id"] = str(uuid.uuid5(NAMESPACE, f"gone:{raw['finding_id']}"))
    out["state"] = "OPEN"
    port = dict(out.get("port") or {})
    port["port"] = EXTRA_PORT_BASE + bucket + int(raw["finding_id"].replace("-", "")[:3], 16) % 500
    out["port"] = port
    return out


def build_records(raws: list[dict[str, Any]]) -> list[dict[str, Any]]:
    cutoff = max(_parse(r["last_found"]) for r in raws) - SHIFT
    out: list[dict[str, Any]] = []
    for raw in raws:
        bucket = _bucket(raw["finding_id"])
        if _parse(raw["first_found"]) > cutoff or bucket == DROP_BUCKET:
            continue
        older = _older(raw, bucket, cutoff)
        out.append(older)
        if bucket == EXTRA_BUCKET:
            out.append(_extra(raw, older, bucket))
    return out


def _check_target(source: Path, target: Path) -> None:
    resolved_source, resolved_target = source.resolve(), target.resolve()
    if resolved_target == resolved_source or resolved_source in resolved_target.parents:
        raise ValueError("the output directory must not be the source or inside it")
    if target.exists() and (not target.is_dir() or any(target.iterdir())):
        raise ValueError("the output directory must be new or empty")


def make_baseline(source: Path, target: Path) -> int:
    """Write the synthetic baseline; return the number of records written."""
    _check_target(source, target)
    raws = [raw for _, _, raw in iter_raw_records(source)]
    if not raws:
        raise ValueError("the source export has no records")
    try:
        records = build_records(raws)
    except (KeyError, TypeError, AttributeError, ValueError) as exc:
        raise ValueError(f"a source record is malformed ({type(exc).__name__}: {exc})") from None
    chunks = target / "chunks"
    chunks.mkdir(parents=True, exist_ok=True)
    (chunks / "chunk_1.json").write_text(
        json.dumps(records, sort_keys=True, separators=(",", ":"), ensure_ascii=False), encoding="utf-8"
    )
    (target / SYNTHETIC_MARKER).write_text(MARKER_TEXT, encoding="utf-8")
    return len(records)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build a synthetic earlier pull from a saved export.")
    parser.add_argument("source", type=Path, help="saved export directory (for example data/sample)")
    parser.add_argument("target", type=Path, help="new or empty output directory")
    args = parser.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(message)s", stream=sys.stderr)
    try:
        written = make_baseline(args.source, args.target)
    except (IngestError, ValueError, OSError) as exc:
        log.error("error: %s", exc)
        return 1
    log.info("wrote %d synthetic baseline records to %s", written, args.target)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
